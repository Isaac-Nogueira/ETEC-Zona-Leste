        <h3>Excelência em Educação Técnica na Região da Zona Leste de São Paulo</h3>
        <p>
            Localizada estrategicamente na Avenida Águia de Haia, na Zona Leste de São Paulo, a Etec Zona Leste se destaca como um 
            importante polo educacional na região. Sua história remonta ao compromisso com a excelência educacional e o desenvolvimento 
            profissional dos estudantes. 
            Fundada em 2008, a Etec Zona Leste rapidamente se estabeleceu como uma instituição de referência no ensino técnico e tecnológico. 
            Desde o início, sua missão foi proporcionar oportunidades de aprendizado que preparassem os alunos para os desafios do mercado de 
            trabalho, além de incentivá-los a buscar a excelência acadêmica. 
            Ao longo dos anos, a escola tem evoluído e se adaptado às demandas da sociedade e do mercado, ampliando sua oferta de cursos e 
            modernizando suas instalações. Com uma equipe dedicada de professores e funcionários, a Etec Zona Leste oferece uma variedade de 
            cursos técnicos em áreas como informática, administração, eletrônica, entre outros, proporcionando aos alunos uma formação sólida e atualizada. 
            Além da excelência acadêmica, a Etec Zona Leste também se destaca por suas atividades extracurriculares, que incluem projetos de pesquisa, 
            competições acadêmicas, eventos culturais e esportivos. Essas atividades complementam o currículo escolar, promovendo o desenvolvimento integral 
            dos estudantes e estimulando o trabalho em equipe, a liderança e a criatividade.
        </p>
