    <div class="prova">
        <h2>A Prova</h2>
        <p>
            A prova do vestibulinho consiste em 50 questões de múltipla escolha, abrangendo várias áreas do conhecimento, incluindo Língua Portuguesa, Matemática, 
            Ciências e questões específicas relacionadas ao curso técnico escolhido. Após a correção das provas, os resultados são divulgados dentro do prazo estabelecido, 
            permitindo que os candidatos verifiquem sua pontuação e classificação. Os aprovados devem então proceder com a matrícula dentro do prazo estabelecido, seguindo 
            as orientações fornecidas pela ETEC, o que inclui a apresentação de documentos e o preenchimento de formulários específicos. 
            É fundamental que você, candidato, esteja atento à modalidade de curso que escolheu, pois o Centro Paula Souza não assume responsabilidade por inscrições em cursos 
            incorretos ou modalidades não desejadas. Certifique-se de selecionar cuidadosamente o curso e a modalidade desejados durante o processo de inscrição, garantindo 
            assim uma participação adequada e de acordo com suas preferências e objetivos educacionais. 
        </p>
