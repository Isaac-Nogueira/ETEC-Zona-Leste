        <p>
            O processo de vestibulinho na ETEC, segue um padrão definido pelo Centro Paula Souza. Primeiramente, é divulgado um edital contendo todas as informações 
            essenciais, como datas, locais de prova, cursos oferecidos, requisitos de inscrição e documentação necessária. 
            Os candidatos devem então se inscrever dentro do prazo estipulado, geralmente de forma online através do site oficial do vestibulinho da ETEC, e pagar uma 
