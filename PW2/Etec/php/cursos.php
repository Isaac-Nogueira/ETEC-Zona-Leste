        <div class="apresentacao">
            <h2>Recursos Humanos</h2>
            <p>
                A formação técnica do curso de Recursos Humanos irá preparar o aluno para realizar as tarefas sob a responsabilidade do setor de Recursos Humanos de uma empresa, como contratação, 
                demissão e aposentadoria de funcionários e oferta de benefícios (vale-transporte, plano de saúde, vale-refeição etc.), entre outras atividades.
            </p>
        </div>
