    <div class="cursos">
        <div class="apresentacao">
            <h2>Logística</h2>
            <p>
                No contexto do aprendizado sobre logística, os estudantes serão expostos a uma variedade de conhecimentos interdisciplinares, incluindo matemática, geografia e física. 
                Essas disciplinas são fundamentais para entender os processos de compra de matérias-primas, a movimentação de estoque e a escolha das melhores rotas de transporte.
                Ao longo do curso, os alunos aprenderão a otimizar a movimentação das cargas e produtos dentro de um estoque, considerando fatores como a utilização de equipamentos adequados, 
                como carrinhos ou empilhadeiras, e o armazenamento correto de diferentes tipos de produto.
            </p>
