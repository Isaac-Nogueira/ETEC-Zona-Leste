    <div class="cursos">
        <div class="apresentacao">
            <h2>Serviços Jurídicos</h2>
            <p>
                O curso oferece uma abordagem abrangente das leis e normas que regem as diferentes esferas da sociedade e das relações comerciais. Os alunos mergulharam em áreas essenciais do Direito, 
                como o direito constitucional, que explora a estrutura e os princípios fundamentais da Constituição Federal. Além disso, estudam o Direito Penal, compreendendo as penalidades para crimes e 
                transgressões legais, e o Direito Civil, que abrange as normas para relações interpessoais e questões familiares. No contexto empresarial, os alunos exploram o Direito empresarial, tratando 
                de transações comerciais entre empresas e indivíduos, e o Direito do Trabalho, que examina os direitos e responsabilidades de empregadores e funcionários. Também são abordadas questões do 
                direito administrativo, que descreve o funcionamento dos órgãos públicos.
            </p>
